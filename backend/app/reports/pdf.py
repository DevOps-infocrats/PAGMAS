"""Server-side weekly report PDF (ReportLab). Built from the same payload as the on-screen preview."""

from __future__ import annotations

import io
from datetime import date

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from ..config import PROJECT_DIR

LOGO = PROJECT_DIR / "frontend" / "public" / "brand" / "pratap-wordmark.png"
BRAND = colors.HexColor("#0877A6")
MUTED = colors.HexColor("#5B6675")
GRID = colors.HexColor("#E4E7EC")
GOOD = colors.HexColor("#0B6E2C")
BAD = colors.HexColor("#B42318")


def _fmt(v, unit: str) -> str:
    if v is None:
        return "NA"
    if unit == "percent":
        return f"{v:,.2f}%"
    if unit == "rkm":
        return f"{v:,.2f} RKM"
    return f"{int(v):,}"


def _delta(cur, prev, unit: str) -> str:
    if cur is None or prev is None:
        return "NA"
    d = cur - prev
    sign = "+" if d > 0 else ("−" if d < 0 else "±")
    if unit == "percent":
        return f"{sign}{abs(d):.2f} pp"
    if unit == "rkm":
        return f"{sign}{abs(d):,.2f}"
    return f"{sign}{abs(int(round(d))):,}"


def _date(iso: str | None) -> str:
    return date.fromisoformat(iso[:10]).strftime("%d %b %Y") if iso else "NA"


def render_weekly_report(r: dict, generated_by: str) -> bytes:
    buf = io.BytesIO()
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Heading1"], fontSize=16, textColor=colors.HexColor("#0E1726"), spaceAfter=2)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=11, textColor=BRAND, spaceBefore=10, spaceAfter=4)
    body = ParagraphStyle("b", parent=styles["BodyText"], fontSize=9, leading=12)
    small = ParagraphStyle("s", parent=body, fontSize=7.5, textColor=MUTED)

    week, cmp = r["week"], r["compareWeek"]

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(MUTED)
        canvas.drawString(15 * mm, 10 * mm, f"Source: {r.get('sourceFile', '')} · data as of {_date(r.get('dataAsOf'))} · generated by {generated_by}")
        canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=14 * mm, bottomMargin=16 * mm, title="Weekly network performance report")
    el: list = []
    if LOGO.exists():
        el.append(Image(str(LOGO), width=34 * mm, height=34 * mm * 67 / 240, hAlign="LEFT"))
        el.append(Spacer(1, 4))
    el.append(Paragraph("Weekly network performance report", h1))
    el.append(
        Paragraph(
            f"{r['scopeLabel']} · {week['label']} ({_date(week['startDate'])} – {_date(week['endDate'])}) compared with {cmp['label']} "
            f"({_date(cmp['startDate'])} – {_date(cmp['endDate'])})",
            small,
        )
    )

    rows = {c["key"]: c for c in r["comparison"]}
    summary = []
    if (a := rows.get("availabilityWeek")) and a["current"] is not None:
        summary.append(f"Average AMC availability for the week was <b>{_fmt(a['current'], 'percent')}</b> ({_delta(a['current'], a['previous'], 'percent')} vs {cmp['label']}).")
    if (m := rows.get("availability")) and m["current"] is not None:
        summary.append(f"Month-to-date AMC availability at week end: <b>{_fmt(m['current'], 'percent')}</b>.")
    if (h := rows.get("hotoDoneGps")) and h["current"] is not None:
        summary.append(f"HOTO completed for <b>{_fmt(h['current'], 'count')}</b> GPs ({_delta(h['current'], h['previous'], 'count')}).")
    if (p := rows.get("penaltyBlocksWeek")) and p["current"] is not None:
        summary.append(f"<b>{_fmt(p['current'], 'count')}</b> penalty-prone blocks this week ({_delta(p['current'], p['previous'], 'count')}).")
    if (z := rows.get("gpsAtZero")) and (n := rows.get("naGps")):
        summary.append(f"{_fmt(z['current'], 'count')} AMC GPs at 0% MTD; {_fmt(n['current'], 'count')} not reported (NA, excluded from averages).")
    el.append(Paragraph("1. Executive summary", h2))
    for s in summary:
        el.append(Paragraph(f"• {s}", body))

    def table(data, widths, align_right_from=1, zebra=True):
        t = Table(data, colWidths=widths, repeatRows=1)
        style = [
            ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8),
            ("FONT", (0, 1), (-1, -1), "Helvetica", 8),
            ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
            ("LINEBELOW", (0, 0), (-1, 0), 0.6, GRID),
            ("LINEBELOW", (0, 1), (-1, -1), 0.3, GRID),
            ("ALIGN", (align_right_from, 0), (-1, -1), "RIGHT"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]
        t.setStyle(TableStyle(style))
        return t

    el.append(Paragraph("2. KPI comparison", h2))
    data = [["Metric", cmp["label"], week["label"], "Change", "Trend"]]
    trend_styles = []
    for i, c in enumerate(r["comparison"], start=1):
        trend = "—"
        if c["current"] is not None and c["previous"] is not None and c["current"] != c["previous"] and c["polarity"] != "neutral":
            better = (c["current"] > c["previous"]) == (c["polarity"] == "up")
            trend = "Better" if better else "Worse"
            trend_styles.append(("TEXTCOLOR", (4, i), (4, i), GOOD if better else BAD))
        data.append([c["label"], _fmt(c["previous"], c["unit"]), _fmt(c["current"], c["unit"]), _delta(c["current"], c["previous"], c["unit"]), trend])
    t = table(data, [70 * mm, 28 * mm, 28 * mm, 28 * mm, 22 * mm])
    t.setStyle(TableStyle(trend_styles))
    el.append(t)
    el.append(Paragraph("Percentage metrics are compared in percentage points (pp). NA values are excluded, never treated as 0.", small))

    el.append(Paragraph("3. Performance ranking (AMC availability, MTD)", h2))
    data = [["#", "Name", "Availability", "Previous", "AMC %", "Penalty blocks"]]
    for i, x in enumerate(r["ranking"][:15], start=1):
        data.append([str(i), x["name"], _fmt(x["availability"], "percent"), _fmt(x["previous"], "percent"), _fmt(x["amcPct"], "percent"), str(x["penaltyBlocks"])])
    el.append(table(data, [8 * mm, 62 * mm, 28 * mm, 28 * mm, 24 * mm, 26 * mm], align_right_from=2))

    el.append(Paragraph("4. HOTO progress & 5. Fibre / AMC changes", h2))
    data = [["Item", "Previous", "Current", "Change"]]
    hp = r["hotoProgress"]
    data.append(["HOTO done GPs", _fmt(hp[0]["done"], "count"), _fmt(hp[1]["done"], "count"), _delta(hp[1]["done"], hp[0]["done"], "count")])
    data.append(["HOTO pending GPs", _fmt(hp[0]["pending"], "count"), _fmt(hp[1]["pending"], "count"), _delta(hp[1]["pending"], hp[0]["pending"], "count")])
    for f in r["fibreChanges"]:
        unit = "rkm" if "RKM" in f["label"] else "count"
        data.append([f["label"], _fmt(f["previous"], unit), _fmt(f["current"], unit), _delta(f["current"], f["previous"], unit)])
    el.append(table(data, [80 * mm, 32 * mm, 32 * mm, 32 * mm]))

    el.append(Paragraph("6. Penalty-prone blocks", h2))
    if r["penaltyBlocks"]:
        data = [["Block", "District", "Circle", "Availability", "Previous"]]
        data += [[b["name"], b["districtName"], b["circleName"], _fmt(b["availability"], "percent"), _fmt(b["previous"], "percent")] for b in r["penaltyBlocks"]]
        el.append(table(data, [45 * mm, 40 * mm, 35 * mm, 28 * mm, 28 * mm], align_right_from=3))
    else:
        el.append(Paragraph("None in this scope.", body))

    el.append(Paragraph("7. Lowest-availability AMC GPs", h2))
    if r["lowAvailabilityGps"]:
        data = [["GP code", "GP", "Block", "Availability"]]
        data += [[g["id"], g["name"], g["blockName"], _fmt(g["availability"], "percent")] for g in r["lowAvailabilityGps"]]
        el.append(table(data, [28 * mm, 60 * mm, 60 * mm, 28 * mm], align_right_from=3))
    else:
        el.append(Paragraph("None below the penalty threshold.", body))

    el.append(KeepTogether([Paragraph("8. Data-quality exceptions", h2), table([["Check", "Count"]] + [[q["label"], f"{q['count']:,}"] for q in r["dataQuality"]], [146 * mm, 30 * mm])]))

    doc.build(el, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
