import { API_MODE, api, type KpiListKind, type KpiListQuery, type PeriodParams, type ReportComparisonRow, type ReportParams, type WeeklyReportResponse } from "@/lib/api";
import { API_BASE, kpiListQuery, reportQuery } from "@/lib/api/http-client";
import { formatDate, formatDelta, formatValue } from "@/lib/utils/format";
import { buildPdf, type PdfLine } from "./demo-pdf";

/**
 * Report generation entry point.
 *  - live mode: the Python backend renders the PDF from the imported data (ReportLab).
 *  - mock mode: builds a clearly watermarked DEMO PDF in the browser.
 */
export async function downloadWeeklyReportPdf(params: ReportParams): Promise<string> {
  if (API_MODE === "live") {
    const res = await fetch(`${API_BASE}/reports/weekly.pdf${reportQuery(params)}`, { credentials: "same-origin" });
    if (!res.ok) throw new Error(`Report generation failed (${res.status})`);
    const name = `weekly_report_${params.weekId}.pdf`;
    save(await res.blob(), name);
    return name;
  }

  const report = await api.getWeeklyReport(params);
  const name = `DEMO_weekly_report_${report.week.label.replace(" ", "")}_vs_${report.compareWeek.label.replace(" ", "")}.pdf`;
  save(buildPdf(reportToLines(report), "Pratap network analytics | DEMO DATA | Not for operational use"), name);
  return name;
}

/** Management Review deck (.pptx) with only the chosen sections / circles, rendered by the backend from the same payload as the web page. */
export async function downloadManagementReviewPptx(p: PeriodParams, pick: { sections: string[]; circles: string[] }): Promise<string> {
  if (API_MODE !== "live") throw new Error("The PPT is generated by the live backend (NEXT_PUBLIC_API_MODE=live).");
  const q = new URLSearchParams({ week: p.weekId, compare: p.compareWeekId, sections: pick.sections.join(",") });
  // Circles only matter for the per-circle sections; omitted = all circles.
  if (pick.circles.length) q.set("circles", pick.circles.join(","));
  const res = await fetch(`${API_BASE}/reviews/management.pptx?${q}`, { credentials: "same-origin", cache: "no-store" });
  if (res.status === 401) {
    window.location.replace(`/login?next=${encodeURIComponent(window.location.pathname + window.location.search)}&expired=1`);
    throw new Error("Your session has ended.");
  }
  if (!res.ok) {
    const detail = await res.json().then((b: { detail?: unknown }) => (typeof b.detail === "string" ? b.detail : null)).catch(() => null);
    throw new Error(detail ?? `PPT generation failed (${res.status})`);
  }
  const name = /filename="([^"]+)"/.exec(res.headers.get("content-disposition") ?? "")?.[1] ?? `Pratap_Management_Review_${p.weekId}.pptx`;
  save(await res.blob(), name);
  return name;
}

/** Whole (filtered) KPI list as an Excel workbook, built by the backend with the same rule as the card. */
export async function downloadKpiListXlsx(kind: KpiListKind, q: KpiListQuery): Promise<string> {
  if (API_MODE !== "live") throw new Error("The Excel file is generated by the live backend (NEXT_PUBLIC_API_MODE=live).");
  const res = await fetch(`${API_BASE}/kpi-lists/${encodeURIComponent(kind)}.xlsx${kpiListQuery({ ...q, page: undefined, pageSize: undefined })}`, { credentials: "same-origin", cache: "no-store" });
  if (res.status === 401) {
    window.location.replace(`/login?next=${encodeURIComponent(window.location.pathname + window.location.search)}&expired=1`);
    throw new Error("Your session has ended.");
  }
  if (!res.ok) {
    const detail = await res.json().then((b: { detail?: unknown }) => (typeof b.detail === "string" ? b.detail : null)).catch(() => null);
    throw new Error(detail ?? `Excel download failed (${res.status})`);
  }
  const name = /filename="([^"]+)"/.exec(res.headers.get("content-disposition") ?? "")?.[1] ?? `Pratap_${kind}.xlsx`;
  save(await res.blob(), name);
  return name;
}

function save(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function changeText(r: ReportComparisonRow): string {
  if (r.current == null || r.previous == null) return "NA";
  return formatDelta(Math.round((r.current - r.previous) * 100) / 100, r.unit);
}

/** Plain-language executive summary derived from the comparison rows. */
export function executiveSummary(report: WeeklyReportResponse): string[] {
  const row = (k: string) => report.comparison.find((c) => c.key === k);
  const out: string[] = [];
  const av = row("availability");
  if (av?.current != null)
    out.push(`Average AMC availability was ${formatValue(av.current, "percent")} in ${report.week.label} (${changeText(av)} vs ${report.compareWeek.label}).`);
  const hoto = row("hotoDoneGps");
  if (hoto?.current != null) out.push(`HOTO completed for ${formatValue(hoto.current, "count")} GPs (${changeText(hoto)} week-on-week).`);
  const pen = row("penaltyBlocks");
  if (pen?.current != null) out.push(`${formatValue(pen.current, "count")} blocks are penalty-prone (below the penalty threshold), ${changeText(pen)} vs last period.`);
  const zero = row("gpsAtZero");
  const na = row("naGps");
  if (zero && na) out.push(`${formatValue(zero.current, "count")} AMC GPs reported 0%, and ${formatValue(na.current, "count")} did not report (NA).`);
  return out;
}

function reportToLines(r: WeeklyReportResponse): PdfLine[] {
  const L: PdfLine[] = [
    { text: "DEMO REPORT - generated from mock data, not a verified production report", size: 9, bold: true, color: [0.7, 0.35, 0] },
    { text: "Weekly network performance report", size: 18, bold: true, gap: 6 },
    { text: `Scope: ${r.scopeLabel}`, size: 10, gap: 4 },
    { text: `${r.week.label} (${formatDate(r.week.startDate)} - ${formatDate(r.week.endDate)}) compared with ${r.compareWeek.label}`, size: 10 },
    { text: "Executive summary", size: 13, bold: true, gap: 14 },
    ...executiveSummary(r).map((t) => ({ text: `- ${t}`, size: 10 })),
    { text: "KPI comparison", size: 13, bold: true, gap: 14 },
    { text: `Metric | ${r.compareWeek.label} | ${r.week.label} | Change`, size: 9, bold: true },
    ...r.comparison.map((c) => ({
      text: `${c.label} | ${formatValue(c.previous, c.unit)} | ${formatValue(c.current, c.unit)} | ${changeText(c)}`,
      size: 9,
    })),
    { text: "Performance ranking (by availability)", size: 13, bold: true, gap: 14 },
    ...r.ranking.slice(0, 15).map((x, i) => ({
      text: `${i + 1}. ${x.name} - ${formatValue(x.availability, "percent")} (prev ${formatValue(x.previous, "percent")}), AMC ${formatValue(x.amcPct, "percent")}, ${x.penaltyBlocks} penalty blocks`,
      size: 9,
    })),
    { text: "Penalty-prone blocks", size: 13, bold: true, gap: 14 },
    ...(r.penaltyBlocks.length
      ? r.penaltyBlocks.map((b) => ({ text: `${b.name} (${b.districtName}, ${b.circleName}) - ${formatValue(b.availability, "percent")}`, size: 9 }))
      : [{ text: "None", size: 9 }]),
    { text: "Low-availability GPs", size: 13, bold: true, gap: 14 },
    ...(r.lowAvailabilityGps.length
      ? r.lowAvailabilityGps.map((g) => ({ text: `${g.name} (${g.blockName}) - ${formatValue(g.availability, "percent")}`, size: 9 }))
      : [{ text: "None", size: 9 }]),
    { text: "Data-quality exceptions", size: 13, bold: true, gap: 14 },
    ...r.dataQuality.map((q) => ({ text: `${q.label}: ${q.count}`, size: 9 })),
  ];
  return L;
}
